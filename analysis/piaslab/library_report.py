"""Generate the library exploratory-analysis report: charts + a markdown synthesis.

Run it like the site build — on demand, regenerating from the current ``data/library.json``:

    cd analysis && uv run python -m piaslab.library_report

Outputs go to ``analysis/reports/library/`` (git-ignored; regenerate rather than commit). The
report is bibliometric/thematic over curated metadata — see ``piaslab.library``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless: no display needed, safe in CI
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from piaslab.library import (  # noqa: E402
    load_library,
    tag_themes,
    term_frequency,
    theme_cooccurrence,
    theme_counts,
    top_theme_pairs,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_LIBRARY = REPO_ROOT / "data" / "library.json"
DEFAULT_OUT = REPO_ROOT / "analysis" / "reports" / "library"

_BAR = "#1f5f8b"


def _save(fig: plt.Figure, path: Path) -> None:
    fig.tight_layout()
    fig.savefig(path, dpi=140, bbox_inches="tight")
    plt.close(fig)


def _chart_categories(df: pd.DataFrame, out: Path) -> None:
    counts = df["category"].value_counts()
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.barh(counts.index[::-1], counts.values[::-1], color=_BAR)
    ax.set_title("Library sources by category")
    ax.set_xlabel("sources")
    _save(fig, out / "categories.png")


def _chart_years(df: pd.DataFrame, out: Path) -> None:
    years = df["year"].dropna().astype(int)
    if years.empty:
        return
    span = range(int(years.min()), int(years.max()) + 1)
    counts = years.value_counts().reindex(span, fill_value=0).sort_index()
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.bar(counts.index, counts.values, color=_BAR)
    ax.set_title("Library sources by year")
    ax.set_xlabel("year")
    ax.set_ylabel("sources")
    _save(fig, out / "years.png")


def _chart_themes(tagged: pd.DataFrame, out: Path) -> None:
    counts = theme_counts(tagged)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.barh(counts.index[::-1], counts.values[::-1], color=_BAR)
    ax.set_title("Sources per theme")
    ax.set_xlabel("sources")
    _save(fig, out / "themes.png")


def _chart_cooccurrence(tagged: pd.DataFrame, out: Path) -> None:
    mat = theme_cooccurrence(tagged)
    fig, ax = plt.subplots(figsize=(8, 7))
    im = ax.imshow(mat.values, cmap="Blues")
    ax.set_xticks(range(len(mat)))
    ax.set_yticks(range(len(mat)))
    ax.set_xticklabels(mat.columns, rotation=45, ha="right", fontsize=8)
    ax.set_yticklabels(mat.index, fontsize=8)
    ax.set_title("Theme co-occurrence (sources sharing both themes)")
    for i in range(len(mat)):
        for j in range(len(mat)):
            v = int(mat.iloc[i, j])
            if v:
                ax.text(j, i, v, ha="center", va="center", fontsize=7,
                        color="white" if v >= mat.values.max() * 0.6 else "black")
    fig.colorbar(im, ax=ax, shrink=0.7)
    _save(fig, out / "cooccurrence.png")


def _synthesis_md(df: pd.DataFrame, tagged: pd.DataFrame) -> str:
    n = len(df)
    research = df[df["is_research"]]
    lines: list[str] = []
    lines.append("# Research library — exploratory analysis\n")
    lines.append(
        f"Bibliometric and thematic view of **{n} sources** in `data/library.json` "
        f"({len(research)} empirical/industry, {n - len(research)} supporting "
        "docs/standards/ethics). "
        "Generated by `piaslab.library_report`; regenerate as the library grows. Themes come from "
        "keyword matching on each source's title and curated note, not from full texts.\n"
    )

    lines.append("## Coverage by category\n")
    for cat, c in df["category"].value_counts().items():
        lines.append(f"- **{cat}**: {c}")
    lines.append("")

    years = df["year"].dropna().astype(int)
    if not years.empty:
        lines.append("## Timeline\n")
        lines.append(
            f"Sources span **{years.min()}–{years.max()}**, "
            f"with {int((years >= 2025).sum())} from 2025 onward — the recent surge in "
            "AI-code-generation and agentic-commerce work.\n"
        )

    lines.append("## Themes\n")
    for theme, c in theme_counts(tagged).items():
        if c:
            lines.append(f"- **{theme}**: {c}")
    lines.append("")

    lines.append("## Strongest intersections\n")
    lines.append(
        "Theme pairs that co-occur across the most sources — "
        "where the literature clusters:\n"
    )
    for a, b, c in top_theme_pairs(tagged, n=8):
        lines.append(f"- {a} ∩ {b}: {c}")
    lines.append("")

    lines.append("## Empirical & industry sources (what each contributes)\n")
    lines.append("From the curated notes; read the source before citing a specific finding.\n")
    for _, r in research.sort_values("year").iterrows():
        yr = "" if pd.isna(r["year"]) else f" ({int(r['year'])})"
        lines.append(f"- **{r['title']}**{yr} — {r['source']}. {r['note']} [link]({r['url']})")
    lines.append("")

    lines.append("## Most frequent content words\n")
    freq = term_frequency(df, n=15)
    lines.append(", ".join(f"{w} ({c})" for w, c in freq.items()) + "\n")

    lines.append("## Charts\n")
    for name in ("categories", "years", "themes", "cooccurrence"):
        lines.append(f"![{name}]({name}.png)")
    lines.append("")
    return "\n".join(lines)


def generate(library: str | Path = DEFAULT_LIBRARY, out_dir: str | Path = DEFAULT_OUT) -> Path:
    """Write charts and ``summary.md`` to ``out_dir``; return the summary path."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    df = load_library(library)
    tagged = tag_themes(df)

    _chart_categories(df, out)
    _chart_years(df, out)
    _chart_themes(tagged, out)
    _chart_cooccurrence(tagged, out)

    summary = out / "summary.md"
    summary.write_text(_synthesis_md(df, tagged), encoding="utf-8")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate the library exploratory-analysis report."
    )
    parser.add_argument("--library", default=str(DEFAULT_LIBRARY))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    summary = generate(args.library, args.out)
    print(f"Wrote {summary} and charts to {summary.parent}")


if __name__ == "__main__":
    main()
