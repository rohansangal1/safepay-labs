// Copies the single source of truth into the static site. Zero dependencies: uses Node's
// built-in type stripper so the browser runs exactly the engine the tests exercise.
import fs from 'node:fs';
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';

const root = path.join(import.meta.dirname, '..');
const from = (...p: string[]) => path.join(root, ...p);
const HEADER = '// Generated by scripts/build-site.ts from packages/core/src/score.ts. Do not edit.\n';

const engine = stripTypeScriptTypes(fs.readFileSync(from('packages/core/src/score.ts'), 'utf8'));
fs.writeFileSync(from('site/score.js'), HEADER + engine);

fs.mkdirSync(from('site/data'), { recursive: true });
fs.copyFileSync(from('packages/core/src/controls.json'), from('site/data/controls.json'));
fs.copyFileSync(from('data/runs/lab-reference.json'), from('site/data/assessments.json'));

console.log('Built site/score.js, site/data/controls.json, site/data/assessments.json');
